def state(return_id, order_id, item_id, file_path):
    audit = db(f"SELECT event,description,CAST(properties AS CHAR),ip_address,user_agent,subject_type FROM activity_logs WHERE subject_id={return_id} AND event='return.requested' ORDER BY id DESC LIMIT 1")
    if audit:
        properties = json.loads(audit[0][2])
        properties.pop("order_id", None)
        audit[0][2] = json.dumps(properties, sort_keys=True, separators=(",", ":"))
    rows = {
        "return": db(f"SELECT status,reason,CAST(total_refund_amount AS CHAR),(consent_event_id IS NOT NULL) FROM returns WHERE id={return_id}"),
        "return_items": db(f"SELECT quantity_returned,CAST(refund_amount AS CHAR),restock,status,refund_status FROM return_items WHERE return_id={return_id} ORDER BY id"),
        "order_item": db(f"SELECT returned_quantity,status FROM order_items WHERE id={item_id} AND order_id={order_id}"),
        "audit": audit,
        "evidence_sha256": hashlib.sha256(file_path.read_bytes()).hexdigest(),
    }
    return rows


def cleanup_order(order_id, customer_id, old_reserved, old_sequence, sequence_exists, name, prefix):
    if order_id:
        ret_ids = db(f"SELECT id FROM returns WHERE order_id={order_id}")
        for ret in ret_ids:
            rid = int(ret[0])
            paths = db(f"SELECT evidence_path FROM returns WHERE id={rid}")
            db(f"DELETE FROM activity_logs WHERE subject_type LIKE '%ReturnRequest' AND subject_id={rid}")
            db(f"DELETE FROM return_items WHERE return_id={rid}")
            db(f"DELETE FROM returns WHERE id={rid}")
            for row in paths:
                for root in PUBLIC_ROOTS:
                    (root / row[0]).unlink(missing_ok=True)
        consent_ids = db(f"SELECT id FROM consent_events WHERE order_id={order_id}")
        for consent in consent_ids:
            cid = int(consent[0])
            db(f"DELETE FROM consent_events WHERE root_event_id={cid}")
            db(f"DELETE FROM consent_events WHERE id={cid}")
        item_ids = db(f"SELECT id FROM order_items WHERE order_id={order_id}")
        ids = ",".join(row[0] for row in item_ids) or "0"
        db(f"DELETE FROM activity_logs WHERE (subject_id={order_id} AND subject_type LIKE '%Order') OR (subject_id IN ({ids}) AND subject_type LIKE '%OrderItem')")
        for sql in [f"DELETE FROM order_initial_report_items WHERE order_id={order_id}",
                    f"DELETE FROM stock_request_items WHERE stock_request_id IN (SELECT id FROM stock_requests WHERE order_id={order_id})",
                    f"DELETE FROM stock_requests WHERE order_id={order_id}", f"DELETE FROM commissions WHERE order_id={order_id}",
                    f"DELETE FROM payment_transactions WHERE order_id={order_id}",
                    f"DELETE FROM stock_movements WHERE reference_type='order' AND reference_id={order_id} AND type='reserve'",
                    f"DELETE FROM shipments WHERE order_id={order_id}", f"DELETE FROM order_items WHERE order_id={order_id}",
                    f"DELETE FROM orders WHERE id={order_id}"]:
            db(sql)
    db(f"UPDATE product_stocks SET quantity_reserved={old_reserved} WHERE agent_id=10 AND product_id=3")
    if sequence_exists:
        db(f"UPDATE settings SET `value`='{old_sequence}' WHERE `key`='orders.invoice_sequence'")
    else:
        db("DELETE FROM settings WHERE `key`='orders.invoice_sequence'")
    # Leave the shared customer until both runtimes have completed.


def main():
    if not db("SELECT DATABASE()")[0][0] == "primeclassy_testing":
        raise RuntimeError("refusing non-testing DB")
    suffix = uuid.uuid4().hex[:12]
    name = "Codex assisted return " + suffix
    idempotency_prefix = "codex-assist-return-" + suffix
    old_reserved = int(db("SELECT quantity_reserved FROM product_stocks WHERE agent_id=10 AND product_id=3")[0][0])
    sequence = db("SELECT `value` FROM settings WHERE `key`='orders.invoice_sequence'")
    sequence_exists = bool(sequence)
    old_sequence = sequence[0][0] if sequence else "0"
    db(f"INSERT INTO crm_customers(agent_id,owner_user_id,name,phone,created_at,updated_at) VALUES(10,14,'{name}','081200000099',UTC_TIMESTAMP(6),UTC_TIMESTAMP(6))")
    customer_id = int(db(f"SELECT id FROM crm_customers WHERE name='{name}' ORDER BY id DESC LIMIT 1")[0][0])
    captured = []
    failures = []
    checks = 0
    contract_cases = {"role_denial": [], "missing_reason": [], "quota_exhausted": [], "revoked_consent": []}
    order_by_runtime = {}
    image_bytes = jpeg()
    try:
        for base in (LARAVEL, GO):
            client = Client(base)
            if client.login("sales@imp010.test") != 200:
                raise RuntimeError(f"sales login failed for {base}")
            order_body = {"items": [{"product_id": 3, "quantity": 1}], "payment_method_code": "bank_transfer",
                          "shipping_method": "pickup", "recipient_name": "Synthetic return recipient",
                          "recipient_phone": "081200000001", "address_line": "Parity test address",
                          "village_id": "32730101", "latitude": -6.9, "longitude": 107.6}
            key = idempotency_prefix + base[-4:]
            status, response = client.request("POST", f"/api/v1/crm/customers/{customer_id}/orders", json.dumps(order_body).encode(),
                                              {"Content-Type": "application/json", "Idempotency-Key": key})
            if status != 201 or not response.get("data"):
                failures.append(f"{base}: synthetic order creation HTTP {status}: {str(response)[:400]}")
                captured.append(None)
                continue
            order_id = int(response["data"]["id"])
            order_by_runtime[base] = order_id
            item_row = db(f"SELECT id,fulfilled_quantity FROM order_items WHERE order_id={order_id} ORDER BY id LIMIT 1")
            if not item_row:
                failures.append(f"{base}: assisted order has no item")
                captured.append(None)
                cleanup_order(order_id, customer_id, old_reserved, old_sequence, sequence_exists, name, idempotency_prefix)
                continue
            item_id = int(item_row[0][0])
            db(f"UPDATE order_items SET status='terkirim',fulfilled_quantity=1 WHERE id={item_id}")
            scope_json = json.dumps([{"order_item_id": item_id, "quantity": 1}], separators=(",", ":"))
            db(f"INSERT INTO consent_events(agent_id,subject_user_id,crm_customer_id,order_id,event_type,purpose,scope,actor_id,policy_version,occurred_at,created_at,updated_at) VALUES(10,13,{customer_id},{order_id},'consent_captured','assisted_return','{scope_json}',14,'consent-v1',UTC_TIMESTAMP(6),UTC_TIMESTAMP(6),UTC_TIMESTAMP(6))")
            consent_id = int(db(f"SELECT id FROM consent_events WHERE order_id={order_id} ORDER BY id DESC LIMIT 1")[0][0])
            consent_root = consent_id
            path = f"/api/v1/orders/{order_id}/assisted-returns"
            invalid_values = [(key, value) for key, value in multipart_values(consent_id, item_id) if key != "reason"]
            invalid_status, invalid_body = client.multipart(path, invalid_values, "return.jpg", image_bytes)
            checks += 1
            contract_cases["missing_reason"].append((invalid_status, normalize(invalid_body)))
            if invalid_status != 422 or "reason" not in invalid_body.get("errors", {}):
                failures.append(f"{base}: missing reason should be validation 422: {invalid_status} {invalid_body}")
            admin_client = Client(base)
            if admin_client.login("admin@imp010.test") != 200:
                raise RuntimeError(f"admin login failed for {base}")
            denied_status, denied_body = admin_client.multipart(path, multipart_values(consent_id, item_id), "return.jpg", image_bytes)
            checks += 1
            contract_cases["role_denial"].append((denied_status, normalize(denied_body)))
            if denied_status != 403:
                failures.append(f"{base}: admin should be denied with 403: {denied_status} {denied_body}")
            concurrent_client = Client(base)
            if concurrent_client.login("sales@imp010.test") != 200:
                raise RuntimeError(f"second sales login failed for {base}")
            with ThreadPoolExecutor(max_workers=2) as pool:
                futures = [pool.submit(client.multipart, path, multipart_values(consent_id, item_id), "return.jpg", image_bytes),
                           pool.submit(concurrent_client.multipart, path, multipart_values(consent_id, item_id), "return.jpg", image_bytes)]
                results = [future.result() for future in futures]
            success_results = [result for result in results if result[0] == 201 and result[1].get("data")]
            quota_results = [result for result in results if result[0] == 422]
            checks += 1
            contract_cases["quota_exhausted"].append((quota_results[0][0], normalize(quota_results[0][1])) if quota_results else None)
            if len(success_results) != 1 or len(quota_results) != 1:
                failures.append(f"{base}: concurrent quota requests must yield one 201 and one 422: {[(x[0], x[1].get('message')) for x in results]}")
            if not success_results:
                captured.append(None)
                cleanup_order(order_id, customer_id, old_reserved, old_sequence, sequence_exists, name, idempotency_prefix)
                continue
            status, body = success_results[0]
            data = body["data"]
            return_id = int(data["id"])
            evidence_relative = urllib.parse.urlparse(data["evidence_url"]).path.replace("/storage/", "", 1)
            evidence = next((root / evidence_relative for root in PUBLIC_ROOTS if (root / evidence_relative).is_file()), None)
            if evidence is None:
                failures.append(f"{base}: returned evidence file not found at {evidence_relative}")
                captured.append(None)
            else:
                captured.append((normalize(data), state(return_id, order_id, item_id, evidence), body.get("message")))
            if quota_results and not quota_results[0][1].get("errors", {}).get("items"):
                failures.append(f"{base}: concurrent quota rejection omitted item errors: {quota_results[0]}")
            # A child dispute invalidates future assisted returns; append-only root/child chain is synthetic.
            db(f"INSERT INTO consent_events(agent_id,subject_user_id,crm_customer_id,order_id,root_event_id,event_type,purpose,scope,actor_id,policy_version,occurred_at,created_at,updated_at) SELECT agent_id,subject_user_id,crm_customer_id,order_id,id,'consent_disputed',purpose,scope,14,'consent-v1',UTC_TIMESTAMP(6),UTC_TIMESTAMP(6),UTC_TIMESTAMP(6) FROM consent_events WHERE id={consent_root}")
            # Different item is unavailable on this order; use same item after resetting return quantities for the status test is unnecessary.
            denied_status, denied = client.multipart(path, multipart_values(consent_id, item_id), "return.jpg", image_bytes)
            checks += 1
            contract_cases["revoked_consent"].append((denied_status, normalize(denied)))
            if denied_status != 422:
                failures.append(f"{base}: disputed consent should return 422, got {denied_status}: {denied}")
            cleanup_order(order_id, customer_id, old_reserved, old_sequence, sequence_exists, name, idempotency_prefix)
        if len(captured) == 2 and all(captured):
            checks += 1
            if captured[0][0] != captured[1][0]:
                failures.append("response mismatch: " + json.dumps(captured[0][0], sort_keys=True) + " vs " + json.dumps(captured[1][0], sort_keys=True))
            checks += 1
            if captured[0][1] != captured[1][1]:
                failures.append("persisted state mismatch: " + json.dumps(captured[0][1], sort_keys=True) + " vs " + json.dumps(captured[1][1], sort_keys=True))
            checks += 1
            if captured[0][2] != captured[1][2]:
                failures.append(f"success message mismatch: {captured[0][2]!r} vs {captured[1][2]!r}")
        for case, outcomes in contract_cases.items():
            checks += 1
            if len(outcomes) == 2 and outcomes[0] != outcomes[1]:
                failures.append(f"{case} response mismatch: {outcomes[0]} vs {outcomes[1]}")
    finally:
        for order_id in order_by_runtime.values():
            cleanup_order(order_id, customer_id, old_reserved, old_sequence, sequence_exists, name, idempotency_prefix)
        db(f"DELETE FROM crm_customers WHERE id={customer_id} AND name='{name}'")
    if failures:
        print(f"assisted return differential: {checks-len(failures)} passed, {len(failures)} failed")
        for failure in failures:
            print("FAIL " + failure)
        return 1
    print(f"assisted return differential: {checks} passed, 0 failed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
