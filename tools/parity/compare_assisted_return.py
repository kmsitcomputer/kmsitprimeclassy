#!/usr/bin/env python3
"""Scoped Laravel ↔ Go differential for POST /orders/{order}/assisted-returns.

Creates one synthetic CRM customer and uses the normal assisted-order endpoint for each runtime.
Only the synthetic orders, consent rows, return rows, files, audit rows, reservation and invoice
sequence are touched; the script refuses to use any database except primeclassy_testing.
"""
import hashlib, http.cookiejar, json, pathlib, subprocess, urllib.error, urllib.parse, urllib.request, uuid
from concurrent.futures import ThreadPoolExecutor

LARAVEL = "http://127.0.0.1:8899"
GO = "http://127.0.0.1:8082"
PROJECT = pathlib.Path(__file__).resolve().parents[2]
PUBLIC_ROOTS = [PROJECT / "backend/storage/app/public", PROJECT / "go-backend/storage/app/public"]


class Client:
    def __init__(self, base):
        self.base = base
        self.jar = http.cookiejar.CookieJar()
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.jar))

    def request(self, method, path, body=None, headers=None):
        h = {"Accept": "application/json", "Origin": self.base, "Referer": self.base + "/",
             "X-Requested-With": "XMLHttpRequest", "User-Agent": "IMP010-assisted-return-parity"}
        if headers:
            h.update(headers)
        token = next((urllib.parse.unquote(c.value) for c in self.jar if c.name == "XSRF-TOKEN"), None)
        if token:
            h["X-XSRF-TOKEN"] = token
        try:
            with self.opener.open(urllib.request.Request(self.base + path, data=body, headers=h, method=method), timeout=45) as r:
                raw = r.read().decode()
                return r.status, json.loads(raw) if raw else None
        except urllib.error.HTTPError as e:
            raw = e.read().decode()
            try:
                return e.code, json.loads(raw)
            except Exception:
                return e.code, {"raw": raw}

    def login(self, email):
        self.request("GET", "/sanctum/csrf-cookie")
        return self.request("POST", "/api/v1/auth/login", json.dumps({"identifier": email, "password": "Secret123!"}).encode(),
                            {"Content-Type": "application/json"})[0]

    def multipart(self, path, values, filename, content):
        boundary = "----IMP010" + uuid.uuid4().hex
        body = bytearray()
        for name, value in values:
            body.extend(f"--{boundary}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n{value}\r\n".encode())
        body.extend(f"--{boundary}\r\nContent-Disposition: form-data; name=\"evidence\"; filename=\"{filename}\"\r\nContent-Type: image/jpeg\r\n\r\n".encode())
        body.extend(content)
        body.extend(f"\r\n--{boundary}--\r\n".encode())
        return self.request("POST", path, bytes(body), {"Content-Type": f"multipart/form-data; boundary={boundary}"})


def db(sql):
    if "primeclassy_testing" not in sql and sql.strip().upper().startswith("USE "):
        raise RuntimeError("test harness attempted a non-testing database")
    sql = sql.replace("`", "\\`").replace('"', '\\"')
    cmd = f'mariadb -uprimeclassy_app -p"$(cat $MARIADB_PASSWORD_FILE)" -N -B primeclassy_testing -e "{sql}"'
    result = subprocess.run(["docker", "exec", "primeclassy-mariadb", "sh", "-lc", cmd], capture_output=True, text=True, timeout=90)
    if result.returncode:
        raise RuntimeError(result.stderr[:500])
    return [line.split("\t") for line in result.stdout.strip().splitlines() if line]


def normalize(value):
    if isinstance(value, dict):
        out = {}
        for key, child in value.items():
            if key in {"id", "order_id", "created_at", "order_item_id"}:
                continue
            if key == "evidence_url" and isinstance(child, str):
                out[key] = "/storage/returns/evidence/<evidence>"
            else:
                out[key] = normalize(child)
        return out
    if isinstance(value, list):
        return [normalize(item) for item in value]
    if isinstance(value, str) and len(value) >= 20 and value[4:5] == "-" and "T" in value:
        return "<timestamp>"
    return value


def multipart_values(consent_id, item_id, quantity=1):
    return [("consent_event_id", str(consent_id)), ("reason", "Synthetic return parity check"),
            ("items[0][order_item_id]", str(item_id)), ("items[0][quantity]", str(quantity))]


